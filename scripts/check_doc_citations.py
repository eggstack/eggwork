#!/usr/bin/env python3
"""Check that the design record and the operator docs cite symbols, not lines.

Operations M008b §5.3 replaces the design record's line-number citations with
symbol citations and requires a mechanical gate to keep them that way. This
script is that gate. It reads every Markdown document under ``architecture/``
and ``docs/`` and rejects four things:

1. a citation in the legacy ``file.rs:NNN`` form — a line number is a property
   of the *text*, not of the *symbol*, and every unrelated edit above the
   target invalidates it;
2. a citation whose named path does not exist;
3. a citation whose named symbol does not exist in the named file;
4. a citation whose path is a bare basename that is not unique in the tree.

The check is deliberately a *symbol* check. A line check proves that a line
exists, not that it says what the citation claims, and it breaks on every
unrelated edit above the target. A symbol check proves that the named thing is
still there and still named that — the property a reader actually relies on.

Canonical citation syntax
-------------------------

A **citation** is a backticked span in a document's prose (fenced code blocks
are not prose and are not scanned) that names a location in this repository.
It is written as either::

    `crates/eggwork-server/src/operations.rs`          # a path
    `crates/eggwork-server/src/operations.rs::doctor`  # a path and a symbol

The rules the parser and the checker apply:

* The path is **repository-relative** and **must contain a directory
  separator or a file extension**. ``crates/eggwork-server/src/lib.rs`` is a
  path; ``eggwork_core::MAX_EVENT_BYTES`` is a Rust path expression, not a
  citation, and is left alone; ``lib.rs::doctor`` *is* a citation, because the
  path part looks like a file, and it is rejected as ambiguous.
* The path is **never a bare basename** unless exactly one file in the tree
  carries that name. ``lib.rs`` names four files and is therefore rejected;
  ``store.rs`` names one and resolves.
* A symbol, when present, is separated from the path by ``::`` and may itself
  be module-qualified (``security_tests::endpoint_rejects_credentials_and_non_tls_schemes``).
* A symbol is matched against the items the named file defines. Rust items are
  recognised: ``fn``, ``pub fn``, ``const``, ``static``, ``struct``, ``enum``
  (and its variants), ``trait`` (and its items), ``impl`` (by its self type),
  ``mod``, ``type``, and ``macro_rules!``. Python items are recognised:
  ``def``, ``class`` (and its members), and module-level assignments.
* A symbol that is ambiguous inside its file is rejected; the citation must
  then name the qualified path. ``operations.rs::new`` is ambiguous when the
  file defines several ``new`` methods; ``operations.rs::DoctorReport::new``
  is not.

Two limits are stated rather than papered over:

* An item **generated by a macro** is not in the symbol table, because the
  table records what the file defines, not what a macro expansion would
  produce. ``crates/eggwork-core/src/lib.rs`` defines the ``id_type!`` macro,
  and the six identity types come out of it; a citation names the macro
  (``crates/eggwork-core/src/lib.rs::id_type``), which is the item a reader
  can actually look up.
* A symbol check proves that the named thing is still there and still named
  that. It does not prove that the thing is the one the sentence means. The
  plan's remedy is the qualified path, and this checker enforces it: an
  ambiguous name is rejected rather than resolved by guesswork.

Scope
-----

The checker verifies citations into **source files** (``.rs`` and ``.py``).
Paths to configuration, release artifacts, and Markdown documents are parsed
but not existence-checked, because a large class of them names files this
repository does not contain: ``release-manifest.json`` and ``install.sh`` are
produced by the release pipeline, and ``spec.json`` is a runtime file the
runner writes. The *legacy line-number form* is rejected for every known
extension, because "no document carries a line-number citation" is the rule,
not "no source file carries one".

The checker fails closed. An unreadable document, an unparsable citation, or
a citation it cannot resolve is a failure; "cannot check" is never reported as
"checked". It enumerates the documents it scans deterministically and prints
them, so a document cannot escape the gate by not being scanned.

``--prove-negative-exit`` exercises the rejection path against a synthetic
fixture, in the same spirit as ``scripts/check_execution_ownership.py``: a
checker that has never been shown to fail is not a gate.
"""

from __future__ import annotations

import argparse
import ast
import os
import re
import sys
import tempfile
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

# The directories whose Markdown is the design record and the operator
# documentation. The plan names exactly these two.
DOCUMENT_DIRECTORIES = ("architecture", "docs")

# Extensions whose contents define symbols. Only these are existence-checked
# and symbol-checked; see the module docstring for why.
SOURCE_EXTENSIONS = (".rs", ".py")

# Extensions that may carry a line number in the legacy citation form. The
# legacy form is rejected for all of them: the rule is that no document in
# this repository carries a line-number citation at all.
LEGACY_EXTENSIONS = (
    ".rs",
    ".py",
    ".toml",
    ".json",
    ".sh",
    ".bash",
    ".yml",
    ".yaml",
    ".md",
    ".txt",
    ".cfg",
    ".in",
    ".ps1",
)

# Directories that never hold citable sources.
IGNORED_DIRECTORIES = frozenset({".git", "__pycache__", "node_modules", ".venv"})

# A line-number citation in the legacy form: a path, a colon, a number.
LEGACY_CITATION_RE = re.compile(
    r"(?P<path>[A-Za-z0-9_./\\-]*[A-Za-z0-9_-]\.[A-Za-z][A-Za-z0-9_]*)\s*:\s*"
    r"(?P<lines>\d+(?:\s*[-–,]\s*\d+)*)"
)

# A bare line-number continuation, e.g. the `:1457` in `lib.rs:1335`, `:1457`.
BARE_LINE_RE = re.compile(r"^:\s*\d+(?:\s*[-–,]\s*\d+)*$")


@dataclass(frozen=True)
class Finding:
    """One rejected citation, anchored to the document and line that carries it."""

    document: str
    line: int
    kind: str
    detail: str

    def render(self) -> str:
        return f"{self.document}:{self.line}: {self.kind}: {self.detail}"


@dataclass(frozen=True)
class ParsedCitation:
    """A parsed citation: what it names, and how it names it."""

    raw: str
    path: str
    symbol: str | None
    legacy_lines: str | None = None


