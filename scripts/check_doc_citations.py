RUST_TOKEN_RE = re.compile(r"[A-Za-z_][A-Za-z0-9_]*|::|[{}();,]|[^\sA-Za-z0-9_]")

RUST_ITEM_KEYWORDS = {
    "fn",
    "const",
    "static",
    "struct",
    "enum",
    "trait",
    "type",
    "union",
    "mod",
}

RUST_NON_ITEM_KEYWORDS = {
    "pub",
    "async",
    "unsafe",
    "extern",
    "default",
    "move",
    "ref",
    "dyn",
    "where",
    "mut",
    "auto",
    "raw",
}


def strip_rust_noise(source: str) -> str:
    """Blank Rust comments and literals, preserving every offset.

    A ``fn`` inside a doc comment or a string literal is not an item, and a
    symbol table that counted it would resolve citations to things that do
    not exist. Offsets are preserved so error messages stay line-accurate.
    """
    out = list(source)
    index = 0
    length = len(source)

    def blank(start: int, end: int) -> None:
        for position in range(start, min(end, length)):
            if out[position] != "\n":
                out[position] = " "

    while index < length:
        if source.startswith("//", index):
            end = source.find("\n", index)
            end = length if end < 0 else end
            blank(index, end)
            index = end
            continue
        if source.startswith("/*", index):
            depth = 1
            cursor = index + 2
            while cursor < length and depth:
                if source.startswith("/*", cursor):
                    depth += 1
                    cursor += 2
                elif source.startswith("*/", cursor):
                    depth -= 1
                    cursor += 2
                else:
                    cursor += 1
            blank(index, cursor)
            index = cursor
            continue
        raw = re.match(r"(?:b)?r(#+)?\"", source[index:])
        if raw is not None:
            hashes = raw.group(1) or ""
            terminator = '"' + hashes
            cursor = index + raw.end()
            end = source.find(terminator, cursor)
            end = length if end < 0 else end + len(terminator)
            blank(index, end)
            index = end
            continue
        if source[index] in "\"'":
            quote = source[index]
            if quote == "'":
                following = source[index + 1] if index + 1 < length else ""
                after = source[index + 2] if index + 2 < length else ""
                if (following.isalpha() or following == "_") and after != "'":
                    index += 1  # A lifetime, not a character literal.
                    continue
            cursor = index + 1
            while cursor < length:
                if source[cursor] == "\\":
                    cursor += 2
                elif source[cursor] == quote:
                    cursor += 1
                    break
                else:
                    cursor += 1
            blank(index, cursor)
            index = cursor
            continue
        index += 1
    return "".join(out)


def rust_tokens(code: str) -> list[str]:
    """Split stripped Rust source into identifiers and punctuation."""
    return RUST_TOKEN_RE.findall(code)


def rust_items(source: str) -> dict[str, str]:
    """Map every item in a Rust file to its qualified path and kind.

    The qualified path of an item is the chain of enclosing scopes joined with
    ``::``: a method in ``impl Foo`` is ``Foo::method``, a test in
    ``mod tests`` is ``tests::test_name``, and a variant of ``enum E`` is
    ``E::Variant``.
    """
    code = strip_rust_noise(source)
    tokens = rust_tokens(code)

    symbols: dict[str, str] = {}
    impl_types: dict[str, str] = {}
    scope: list[str] = []
    pending_scope: str | None = None
    enum_pending: str | None = None
    enum_body_depth: int | None = None
    expect: str | None = None
    macro_pending = False
    impl_collecting = False
    impl_candidates: list[str] = []
    angle_depth = 0

    def qualify(name: str) -> str:
        return "::".join([*scope, name]) if scope else name

    def record(name: str, kind: str) -> None:
        symbols.setdefault(qualify(name), kind)

    index = 0
    total = len(tokens)
    while index < total:
        token = tokens[index]
        previous = tokens[index - 1] if index else ""

        if token == "{":
            if impl_collecting:
                impl_collecting = False
                self_type = impl_candidates[-1] if impl_candidates else ""
                if self_type:
                    impl_types.setdefault(self_type, "impl")
                    pending_scope = self_type
                impl_candidates = []
            if pending_scope is not None:
                scope.append(pending_scope)
                if enum_pending == pending_scope:
                    enum_body_depth = len(scope)
                pending_scope = None
            else:
                scope.append("")
            enum_pending = None
            index += 1
            continue
        if token == "}":
            if scope:
                scope.pop()
            if enum_body_depth is not None and len(scope) < enum_body_depth:
                enum_body_depth = None
            index += 1
            continue
        if token == "<":
            angle_depth += 1
            index += 1
            continue
        if token == ">":
            angle_depth = max(0, angle_depth - 1)
            index += 1
            continue
        if token == ";":
            pending_scope = None
            impl_collecting = False
            impl_candidates = []
            index += 1
            continue

        if not (token[0].isalpha() or token[0] == "_"):
            index += 1
            continue

        if expect is not None:
            if token == "fn" and expect == "const":
                expect = "fn"
                index += 1
                continue
            kind = expect
            expect = None
            record(token, kind)
            if kind in {"fn", "mod", "trait"}:
                pending_scope = token
            elif kind == "enum":
                pending_scope = token
                enum_pending = token
            else:
                pending_scope = None
            index += 1
            continue

        if macro_pending:
            macro_pending = False
            record(token, "macro")
            index += 1
            continue

        if token == "impl":
            impl_collecting = True
            impl_candidates = []
            index += 1
            continue

        if token == "for" and impl_collecting:
            impl_candidates = []
            index += 1
            continue

        if impl_collecting:
            if angle_depth == 0:
                impl_candidates.append(token)
            index += 1
            continue

        if token == "macro_rules":
            # The macro's name is the next identifier; the `!` between them is
            # punctuation and is skipped.
            macro_pending = True
            index += 1
            continue
        if token in RUST_ITEM_KEYWORDS:
            expect = token
            index += 1
            continue
        if token in RUST_NON_ITEM_KEYWORDS:
            index += 1
            continue

        # An enum variant: an identifier in a variant position.
        if enum_body_depth is not None and len(scope) == enum_body_depth:
            if previous in {"{", ","} and token not in RUST_ITEM_KEYWORDS:
                following = tokens[index + 1] if index + 1 < total else ""
                if following in {",", "(", "{", "=", "[", "}"}:
                    record(token, "variant")
        index += 1

    for name, kind in impl_types.items():
        symbols.setdefault(name, kind)
    return symbols


