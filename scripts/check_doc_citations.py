FIXTURE_RUST = """\
// A fixture source file. The citations below name things that exist here.
pub const REAL_CONSTANT: usize = 7;
static REAL_STATIC: usize = 9;
pub struct RealStruct {
    pub field: usize,
}
pub enum RealEnum {
    First,
    Second,
}
pub trait RealTrait {
    fn trait_method(&self);
}
pub type RealAlias = usize;
pub mod real_module {
    pub fn module_function() {}
}
macro_rules! real_macro {
    () => {};
}
pub fn real_function() {}
impl RealStruct {
    pub fn real_method(&self) -> usize {
        self.field
    }
}
"""

FIXTURE_PYTHON = """\
REAL_CONSTANT = 3


def real_function():
    return REAL_CONSTANT
"""


def build_fixture_tree(root: Path) -> None:
    """Materialise the synthetic tree the negative-exit proof checks."""
    (root / "architecture").mkdir(parents=True, exist_ok=True)
    (root / "docs").mkdir(parents=True, exist_ok=True)
    (root / "crates" / "demo" / "src").mkdir(parents=True, exist_ok=True)
    (root / "crates" / "other" / "src").mkdir(parents=True, exist_ok=True)
    (root / "scripts").mkdir(parents=True, exist_ok=True)
    (root / "crates" / "demo" / "src" / "lib.rs").write_text(FIXTURE_RUST, encoding="utf-8")
    (root / "crates" / "other" / "src" / "lib.rs").write_text(
        "pub fn unrelated() {}\n", encoding="utf-8"
    )
    (root / "scripts" / "demo.py").write_text(FIXTURE_PYTHON, encoding="utf-8")
    (root / "architecture" / "good.md").write_text(
        "A correct citation names a symbol that exists: "
        "`crates/demo/src/lib.rs::real_function`.\n",
        encoding="utf-8",
    )
    (root / "architecture" / "bad.md").write_text(
        "A wrong citation names a symbol that does not exist: "
        "`crates/demo/src/lib.rs::no_such_symbol`.\n"
        "A legacy citation names a line: `crates/demo/src/lib.rs:12`.\n"
        "An ambiguous basename: `lib.rs::real_function`.\n"
        "A missing file: `crates/demo/src/absent.rs::real_function`.\n",
        encoding="utf-8",
    )


def prove_negative_exit() -> int:
    """Prove the checker rejects a deliberately wrong citation.

    The proof runs the *production* check over a synthetic tree and asserts
    that the deliberately wrong citations are rejected while the correct one
    is accepted. A checker that accepts everything, or that fails to look at
    all, fails this proof.
    """
    with tempfile.TemporaryDirectory(prefix="eggwork-citation-proof-") as directory:
        root = Path(directory)
        build_fixture_tree(root)
        findings, scanned = check_tree(root)

        by_document: dict[str, list[Finding]] = {}
        for finding in findings:
            by_document.setdefault(finding.document, []).append(finding)

        good = by_document.get("architecture/good.md", [])
        bad = by_document.get("architecture/bad.md", [])

        if good:
            print(
                "doc citation guard failed: negative-exit proof regression — "
                "a correct citation was rejected",
                file=sys.stderr,
            )
            for finding in good:
                print(f"- {finding.render()}", file=sys.stderr)
            return 1

        expected = {"unresolved-symbol", "legacy-line-citation", "unresolved-path"}
        observed = {finding.kind for finding in bad}
        missing = expected - observed
        if missing:
            print(
                "doc citation guard failed: negative-exit proof regression — "
                "the deliberately wrong citation was not rejected "
                f"({', '.join(sorted(missing))})",
                file=sys.stderr,
            )
            return 1

        if len(scanned) != 2:
            print(
                "doc citation guard failed: negative-exit proof regression — "
                f"expected 2 fixture documents, scanned {len(scanned)}",
                file=sys.stderr,
            )
            return 1

    print(
        "doc citation guard negative-exit proof passed: the deliberately wrong "
        f"citation was rejected ({', '.join(sorted(observed))}); the correct "
        "citation was accepted"
    )
    return 0


