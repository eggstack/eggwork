# The check
# --------------------------------------------------------------------------


def resolve_symbol(symbols: dict[str, str], wanted: str) -> tuple[str | None, str | None]:
    """Resolve a cited symbol against the items a file defines."""
    if wanted in symbols:
        return wanted, None
    if "::" in wanted:
        return None, f"symbol not found in the cited file: {wanted}"
    candidates = sorted(name for name in symbols if name.rsplit("::", 1)[-1] == wanted)
    if len(candidates) == 1:
        return candidates[0], None
    if len(candidates) > 1:
        listed = ", ".join(candidates[:8])
        return None, (
            f"symbol {wanted} is ambiguous in the cited file; name the qualified "
            f"path (candidates: {listed})"
        )
    return None, f"symbol not found in the cited file: {wanted}"


def check_document(root: Path, document: Path, tree: list[Path]) -> list[Finding]:
    """Every rejected citation in one document."""
    findings: list[Finding] = []
    relative = str(document.relative_to(root))
    try:
        text = document.read_text(encoding="utf-8")
    except OSError as error:
        return [Finding(relative, 1, "unreadable-document", str(error))]

    prose = mask_fenced_code(text)
    legacy_seen: set[tuple[int, str]] = set()

    def report_legacy(line: int, raw: str) -> None:
        key = (line, raw)
        if key in legacy_seen:
            return
        legacy_seen.add(key)
        findings.append(
            Finding(
                relative,
                line,
                "legacy-line-citation",
                f"`{raw}` names a line number; cite a symbol instead",
            )
        )

    # A legacy line-number citation anywhere in the prose, in or out of a code
    # span. The rule is that no document carries a line number.
    for match in LEGACY_CITATION_RE.finditer(prose):
        path = match.group("path")
        extension = f".{path.rsplit('.', 1)[-1].lower()}"
        if extension not in LEGACY_EXTENSIONS:
            continue
        if "://" in path:
            continue
        report_legacy(line_of(prose, match.start()), match.group(0))

    for start, _end, content in code_spans(prose):
        parsed = parse_citation(content)
        if parsed is None:
            continue
        line = line_of(prose, start)

        if parsed.legacy_lines is not None:
            report_legacy(line, parsed.raw)
            continue

        if "::" in parsed.raw and (not parsed.path or not parsed.symbol):
            findings.append(
                Finding(
                    relative,
                    line,
                    "unparsable-citation",
                    f"`{parsed.raw}` is not a path and a symbol",
                )
            )
            continue

        if Path(parsed.path).suffix.lower() not in SOURCE_EXTENSIONS:
            # Not a source file: a configuration path, a release artifact, or a
            # Markdown cross-reference. Parsed, but not verifiable here.
            continue

        resolved, reason = resolve_path(root, parsed.path, tree)
        if resolved is None:
            findings.append(Finding(relative, line, "unresolved-path", reason or ""))
            continue

        if parsed.symbol is None:
            continue

        try:
            symbols = file_symbols(resolved)
        except (OSError, SyntaxError, ValueError) as error:
            findings.append(
                Finding(
                    relative,
                    line,
                    "unreadable-source",
                    f"{resolved.relative_to(root)}: {error}",
                )
            )
            continue

        _name, symbol_reason = resolve_symbol(symbols, parsed.symbol)
        if symbol_reason is not None:
            findings.append(Finding(relative, line, "unresolved-symbol", symbol_reason))

    return findings


def documents(root: Path) -> list[Path]:
    """Every Markdown document the gate covers, deterministically ordered."""
    found: list[Path] = []
    for directory in DOCUMENT_DIRECTORIES:
        base = root / directory
        if not base.is_dir():
            continue
        found.extend(path for path in base.rglob("*.md") if path.is_file())
    return sorted(found)


def check_tree(root: Path) -> tuple[list[Finding], list[Path]]:
    """Check every document under the gate, returning findings and what was scanned."""
    scanned = documents(root)
    if not scanned:
        return (
            [
                Finding(
                    str(Path(*DOCUMENT_DIRECTORIES)),
                    1,
                    "no-documents",
                    "the gate found no documents to scan; the document set must not "
                    "be empty",
                )
            ],
            scanned,
        )
    findings: list[Finding] = []
    tree = repository_files(root)
    for document in scanned:
        findings.extend(check_document(root, document, tree))
    return findings, scanned


