def parse_args(argv: list[str]) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=(
            "Check that architecture/ and docs/ cite symbols rather than line "
            "numbers, and that every cited path and symbol resolves."
        ),
    )
    parser.add_argument(
        "--root",
        default=str(ROOT),
        help="repository root to check (default: the repository this script lives in)",
    )
    parser.add_argument(
        "--prove-negative-exit",
        action="store_true",
        help="Deterministically exercise the checker's rejection path against a "
        "synthetic fixture and exit 0 if the wrong citation is rejected.",
    )
    parser.add_argument(
        "--list-documents",
        action="store_true",
        help="print the documents the gate covers and exit without checking them",
    )
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = parse_args(sys.argv[1:] if argv is None else argv)
    root = Path(args.root).resolve()

    if args.prove_negative_exit:
        return prove_negative_exit()

    if args.list_documents:
        for document in documents(root):
            print(document.relative_to(root))
        return 0

    try:
        findings, scanned = check_tree(root)
    except OSError as error:
        print(f"doc citation guard failed: {error}", file=sys.stderr)
        return 1
    except Exception as error:  # noqa: BLE001 — the gate fails closed, never open.
        print(
            f"doc citation guard failed: the checker itself raised {type(error).__name__}: {error}",
            file=sys.stderr,
        )
        return 1

    print(f"doc citation guard scanned {len(scanned)} documents:")
    for document in scanned:
        print(f"  {document.relative_to(root)}")

    if findings:
        print("doc citation guard failed:", file=sys.stderr)
        for finding in findings:
            print(f"- {finding.render()}", file=sys.stderr)
        print(
            f"doc citation guard failed: {len(findings)} rejected citations",
            file=sys.stderr,
        )
        return 1

    print("doc citation guard passed; every citation names a symbol that resolves")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
