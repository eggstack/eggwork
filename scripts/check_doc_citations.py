# Document scanning
# --------------------------------------------------------------------------


def mask_fenced_code(text: str) -> str:
    """Blank fenced code blocks while preserving line numbering.

    Fenced blocks hold commands and payloads, not citations. A shell snippet
    naming ``$ROOT/node.json`` is an instruction, and a JSON payload naming a
    check is output; neither is a reference to a location in this repository.
    """
    out: list[str] = []
    fence: str | None = None
    for line in text.split("\n"):
        stripped = line.lstrip()
        if fence is None:
            if stripped.startswith("```") or stripped.startswith("~~~"):
                fence = stripped[:3]
                out.append("")
                continue
            out.append(line)
        else:
            if stripped.startswith(fence):
                fence = None
            out.append("")
    return "\n".join(out)


def code_spans(text: str) -> list[tuple[int, int, str]]:
    """Return ``(start, end, content)`` for every inline code span.

    A span opens and closes with the same run of backticks, so a double
    backtick span may contain a single backtick.
    """
    spans: list[tuple[int, int, str]] = []
    index = 0
    length = len(text)
    while index < length:
        if text[index] != "`":
            index += 1
            continue
        run = 0
        while index + run < length and text[index + run] == "`":
            run += 1
        fence = "`" * run
        close = text.find(fence, index + run)
        if close == -1:
            index += run
            continue
        spans.append((index, close + run, text[index + run : close]))
        index = close + run
    return spans


def looks_like_path(text: str) -> bool:
    """Whether a span could name a file rather than a Rust path expression.

    ``crates/eggwork-server/src/lib.rs`` and ``lib.rs`` are paths.
    ``ExecutionStore::open`` and ``eggwork_core::MAX_EVENT_BYTES`` are Rust
    path expressions: the part before ``::`` is a type or a crate, not a file,
    so they are symbol mentions and not citations.
    """
    if "/" in text:
        return True
    name, _, extension = text.rpartition(".")
    return bool(name) and extension.isalpha() and not text.startswith(".")


def parse_citation(raw: str) -> ParsedCitation | None:
    """Parse a backticked span into a citation, or ``None`` when it is prose."""
    text = raw.strip()
    if not text or any(character.isspace() for character in text):
        # A command, a phrase, or a Rust expression with spaces in it. Not a
        # citation: it names no single location.
        return None

    legacy = LEGACY_CITATION_RE.fullmatch(text)
    if legacy is not None:
        extension = f".{legacy.group('path').rsplit('.', 1)[-1].lower()}"
        if extension in LEGACY_EXTENSIONS:
            return ParsedCitation(
                raw=text,
                path=legacy.group("path"),
                symbol=None,
                legacy_lines=legacy.group("lines"),
            )
    if BARE_LINE_RE.match(text):
        # A bare line-number continuation of a preceding citation.
        return ParsedCitation(raw=text, path="", symbol=None, legacy_lines=text.lstrip(": "))

    if "::" in text:
        path, _, symbol = text.partition("::")
        # A call-notation suffix is the same symbol; the canonical form omits it.
        # `id_type!` names the macro `id_type`.
        symbol = symbol.removesuffix("()").removesuffix("!")
        if not path or not symbol:
            if not looks_like_path(path):
                # `eggpack::` and `landlock::` are Rust path prefixes, not
                # citations: they name no location in this repository.
                return None
            return ParsedCitation(raw=text, path=path, symbol=symbol or None)
        if not looks_like_path(path):
            # `ExecutionStore::open` — a Rust path expression, not a citation.
            return None
        return ParsedCitation(raw=text, path=path, symbol=symbol)

    if looks_like_path(text):
        return ParsedCitation(raw=text, path=text, symbol=None)
    return None


def line_of(text: str, offset: int) -> int:
    """The 1-based line number of ``offset`` within ``text``."""
    return text.count("\n", 0, offset) + 1


