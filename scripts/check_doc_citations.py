def repository_files(root: Path) -> list[Path]:
    """Every file in the tree, deterministically ordered, minus build output."""
    files: list[Path] = []
    for directory, subdirectories, names in os.walk(root):
        subdirectories[:] = sorted(
            name
            for name in subdirectories
            if name not in IGNORED_DIRECTORIES and not name.startswith("target")
        )
        for name in sorted(names):
            files.append(Path(directory) / name)
    return files


def resolve_path(
    root: Path, citation_path: str, tree: list[Path]
) -> tuple[Path | None, str | None]:
    """Resolve a citation path to a file, or explain why it cannot be resolved.

    Returns ``(resolved, None)`` on success and ``(None, reason)`` otherwise.
    """
    if not citation_path:
        return None, "citation names no path"
    if citation_path.startswith(("/", "~")):
        return None, f"citation path must be repository-relative: {citation_path}"
    if ".." in Path(citation_path).parts:
        return None, f"citation path must not escape the repository: {citation_path}"

    candidate = root / citation_path
    if candidate.is_file():
        return candidate, None

    if any(character in citation_path for character in "*?"):
        matches = sorted(root.glob(citation_path))
        if matches:
            return matches[0], None
        return None, f"citation path matches no file in the tree: {citation_path}"

    if "/" in citation_path:
        return None, f"citation path does not exist: {citation_path}"

    matches = [path for path in tree if path.name == citation_path]
    if len(matches) == 1:
        return matches[0], None
    if not matches:
        return None, f"citation path does not exist in the tree: {citation_path}"
    candidates = ", ".join(str(path.relative_to(root)) for path in matches[:8])
    return None, (
        f"citation path is a bare basename and is ambiguous in the tree "
        f"({len(matches)} matches: {candidates}); name the full repository path"
    )


