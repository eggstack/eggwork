def python_items(source: str) -> dict[str, str]:
    """Map every item in a Python file to its qualified path and kind."""
    tree = ast.parse(source)
    symbols: dict[str, str] = {}

    def qualify(scope: list[str], name: str) -> str:
        return "::".join([*scope, name]) if scope else name

    def walk(body: list[ast.stmt], scope: list[str]) -> None:
        for node in body:
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                qualified = qualify(scope, node.name)
                symbols.setdefault(qualified, "def")
                walk(node.body, [*scope, node.name])
            elif isinstance(node, ast.ClassDef):
                qualified = qualify(scope, node.name)
                symbols.setdefault(qualified, "class")
                walk(node.body, [*scope, node.name])
            elif isinstance(node, ast.Assign):
                for target in node.targets:
                    if isinstance(target, ast.Name):
                        symbols.setdefault(qualify(scope, target.id), "assignment")
            elif isinstance(node, ast.AnnAssign):
                if isinstance(node.target, ast.Name):
                    symbols.setdefault(qualify(scope, node.target.id), "assignment")
            elif isinstance(node, (ast.If, ast.Try)):
                walk(node.body, scope)
                walk(node.orelse, scope)
                walk(getattr(node, "finalbody", []), scope)
                for handler in getattr(node, "handlers", []):
                    walk(handler.body, scope)
            elif isinstance(node, (ast.With, ast.AsyncWith)):
                walk(node.body, scope)
            elif isinstance(node, (ast.For, ast.AsyncFor, ast.While)):
                walk(node.body, scope)
                walk(node.orelse, scope)

    walk(tree.body, [])
    return symbols


def file_symbols(path: Path) -> dict[str, str]:
    """The symbols a source file defines, keyed by qualified name."""
    source = path.read_text(encoding="utf-8")
    if path.suffix == ".rs":
        return rust_items(source)
    if path.suffix == ".py":
        return python_items(source)
    return {}


