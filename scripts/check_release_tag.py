#!/usr/bin/env python3
"""Pre-tag guard for Eggwork releases: the tag, the version, and the lock agree.

Two staged releases failed for reasons this script would have caught locally:

- `v0.1.3` never staged because the version bump changed `Cargo.toml` without
  regenerating `Cargo.lock`, so every `--locked` release build failed closed.
- `v0.1.4` staged binaries reporting `0.1.3` because the version bump was
  missed entirely, and hosted qualification correctly refused them with
  `installed-daemon-version: daemon reports '0.1.3', expected 0.1.4`.

Two halves, and only one of them needs a tag
------------------------------------------------

``--coherence``
    The **tag-independent** half: the workspace manifest's version and the
    versions `Cargo.lock` pins for this repository's own packages agree with
    each other. This needs no tag, so CI runs it on every push and pull
    request — it is exactly the condition that broke the `v0.1.3` release
    attempt.

``TAG``
    The **release gate**: the tag about to be created names the manifest's
    version, and the lock agrees. The tag-to-version link cannot live in CI:
    the generated release workflow is producer authority (the `release-drift`
    job rejects hand edits to it), and CI never knows the future tag. So this
    half is run by whoever cuts the tag, before the tag exists:

        python3 scripts/check_release_tag.py v0.1.5

    **Where the gate runs today.** This script is the only place in the
    repository where a tag and a version are compared, and it is executed by
    a person, at tag time, on their own checkout. No automated job runs the
    tag half, because no automated job knows the tag. The release workflow
    (`.github/workflows/release.yml`) is generated by `eggpack ci generate`
    from `release/eggpack/`, so wiring the guard into that workflow is an
    upstream Eggpack change and is recorded as such in
    `architecture/release-qualification.md`; until it lands, the tag half is a
    process requirement, not an automated one.

One reader for the manifest, one reader for the lock
-----------------------------------------------------

The workspace version is read by the shared reader in
`scripts/release_candidate_probe.py`, which parses `Cargo.toml` with a real
TOML reader and scopes the read to `[workspace.package].version`. The lock is
parsed with a real TOML reader too: a guard that decides whether a release may
be tagged must not depend on the layout of the files it reads.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parent))
import release_candidate_probe as probe  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
MAX_LOCK_BYTES = 8 * 1024 * 1024


class TagGuardFailure(Exception):
    """The release identity under test could not be read at all."""


def workspace_version(root: Path | None = None) -> str:
    """The workspace version, read by the repository's one shared reader."""
    return probe.workspace_version(root)


def _read_lock(root: Path) -> dict[str, Any]:
    """Parse `Cargo.lock` with a real TOML reader."""
    import tomllib

    lock = root / "Cargo.lock"
    try:
        with lock.open("rb") as handle:
            raw = handle.read(MAX_LOCK_BYTES + 1)
    except OSError as error:
        raise TagGuardFailure("Cargo.lock is unreadable") from error
    if len(raw) > MAX_LOCK_BYTES:
        raise TagGuardFailure("Cargo.lock exceeds the size bound")
    try:
        document = tomllib.loads(raw.decode("utf-8"))
    except (UnicodeDecodeError, tomllib.TOMLDecodeError) as error:
        raise TagGuardFailure("Cargo.lock is not valid TOML") from error
    if not isinstance(document, dict):
        raise TagGuardFailure("Cargo.lock is not a TOML table")
    return document


def lock_versions(root: Path | None = None) -> dict[str, str]:
    """The versions `Cargo.lock` pins for this repository's own packages.

    A lock entry with no `source` is a package built from this repository;
    every other entry is a registry or git dependency whose version is not
    ours to assert. Selecting the repository's own packages by that
    structural property — rather than by a remembered name prefix — keeps the
    rule true when a package is renamed or added.
    """
    base = Path(root) if root is not None else ROOT
    document = _read_lock(base)
    packages = document.get("package")
    if not isinstance(packages, list):
        raise TagGuardFailure("Cargo.lock declares no package list")
    found: dict[str, str] = {}
    for package in packages:
        if not isinstance(package, dict) or "source" in package:
            continue
        name = package.get("name")
        version = package.get("version")
        if isinstance(name, str) and isinstance(version, str):
            found[name] = version
    return found


def workspace_member_names(root: Path | None = None) -> set[str]:
    """The package names the workspace manifest declares as its own members.

    The member list is the manifest's; each member's package name comes from
    that member's own manifest, because a member inherits the workspace
    version rather than carrying one of its own.
    """
    base = Path(root) if root is not None else ROOT
    try:
        document = probe.read_manifest(base)
    except probe.ValidationFailure:
        return set()
    workspace = document.get("workspace")
    members = workspace.get("members") if isinstance(workspace, dict) else None
    if not isinstance(members, list):
        return set()
    names: set[str] = set()
    for member in members:
        if not isinstance(member, str):
            continue
        for directory in _member_directories(base, member):
            try:
                manifest = probe.read_manifest(directory)
            except probe.ValidationFailure:
                continue
            package = manifest.get("package")
            name = package.get("name") if isinstance(package, dict) else None
            if isinstance(name, str) and name:
                names.add(name)
    return names


def _member_directories(base: Path, member: str) -> list[Path]:
    """Resolve one workspace member entry to the directories it names."""
    if any(character in member for character in "*?["):
        return sorted(path for path in base.glob(member) if path.is_dir())
    directory = base / member
    return [directory] if directory.is_dir() else []


def tag_version(tag: str) -> str:
    """The version a tag names.

    A tag may carry a `v` prefix and a version may not; that single
    difference is the only thing permitted between the two.
    """
    return tag[1:] if tag.startswith("v") else tag


def coherence_failures(root: Path | None = None) -> list[str]:
    """The tag-independent half: the manifest and the lock agree.

    Every package the workspace declares must be pinned in the lock, and every
    package the lock records as built from this repository must be pinned at
    the workspace version. This half needs no tag, so CI runs it on every
    push and pull request.
    """
    version = workspace_version(root)
    failures: list[str] = []
    locked = lock_versions(root)
    for name in sorted(workspace_member_names(root)):
        if name not in locked:
            failures.append(f"Cargo.lock does not pin the workspace member {name!r}")
    for name, pinned in sorted(locked.items()):
        if pinned != version:
            failures.append(f"Cargo.lock pins {name} at {pinned!r}, expected {version!r}")
    return failures


def tag_failures(tag: str, root: Path | None = None) -> list[str]:
    """The release gate: the tag names the manifest's version.

    This is the only comparison of a tag against a version in the
    repository. The qualification harness delegates to it rather than
    repeating it.
    """
    version = workspace_version(root)
    expected = tag_version(tag)
    if version != expected:
        return [
            f"workspace version is {version!r}, tag {tag!r} expects {expected!r}"
        ]
    return []


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Check that the tag, the workspace version, and the lock agree.",
        epilog=(
            "Without a tag, only the tag-independent coherence half is checked. "
            "The tag half is the release gate and is run by whoever cuts the tag."
        ),
    )
    parser.add_argument(
        "tag",
        nargs="?",
        help="exact tag about to be created, e.g. v0.1.5",
    )
    parser.add_argument(
        "--coherence",
        action="store_true",
        help=(
            "check only the manifest/lock version coherence, which needs no tag; "
            "this is what CI runs on every push and pull request"
        ),
    )
    args = parser.parse_args(argv)
    if args.coherence and args.tag:
        parser.error("pass either a tag or --coherence, not both")
    if not args.coherence and not args.tag:
        parser.error("a tag is required, or pass --coherence for the tag-independent half")

    try:
        failures = coherence_failures()
    except (TagGuardFailure, probe.ValidationFailure) as error:
        print("release tag guard FAILED:", file=sys.stderr)
        print(f"  - {error}", file=sys.stderr)
        return 1

    if args.tag:
        try:
            failures = failures + tag_failures(args.tag)
        except (TagGuardFailure, probe.ValidationFailure) as error:
            print("release tag guard FAILED:", file=sys.stderr)
            print(f"  - {error}", file=sys.stderr)
            return 1

    if failures:
        print("release tag guard FAILED:", file=sys.stderr)
        for failure in failures:
            print(f"  - {failure}", file=sys.stderr)
        print("bump Cargo.toml, regenerate the lock, rerun the gates, then tag.",
              file=sys.stderr)
        return 1
    if args.tag:
        version = workspace_version()
        print(f"tag {args.tag!r} matches workspace version and lock ({version})")
    else:
        version = workspace_version()
        print(f"workspace version and lock agree ({version})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
